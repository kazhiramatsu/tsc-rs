// Independent binder API evidence; these tables do not qualify command emit.
// node scripts/observe-utf16-binder-names.mjs --write|--check
import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import {spawnSync} from "node:child_process";
import ts from "../vendor/typescript-6.0.3/lib/typescript.js";

const cases = [
  {id: "class-distinct-and-paired", kind: "ClassDeclaration", table: "members", source: String.raw`class C { "\uD800" = 1; "\uD801" = 2; "\uDC00" = 3; "\uFFFD" = 4; "\\uD800" = 5; "__call" = 6; "\uD83D\uDE00" = 7; "\u{1f600}" = 8; }`},
  {id: "computed-object-names", kind: "ObjectLiteralExpression", table: "members", source: String.raw`const o = { ["\uD800"]: 1, ["\uD801"]: 2, ["\uDC00"]: 3, ["\uFFFD"]: 4, ["__call"]: 5, ["\uD800"]: 6 };`},
  {id: "internal-and-user-call", kind: "InterfaceDeclaration", table: "members", source: String.raw`interface I { (): void; "__call": string; ["\uD800"]: number; }`},
  {id: "ambient-module-identity", kind: "SourceFile", table: "locals", source: String.raw`declare module "\uD800" {} declare module "\uD801" {} declare module "\uFFFD" {} declare module "\\uD800" {} declare module "a\uD800*z\uDC00" {}`},
  {id: "arbitrary-export-names", kind: "SourceFile", table: "exports", source: String.raw`const foo = 1; export { foo as "\uD800", foo as "\uD801", foo as "\uFFFD", foo as "__call" };`},
  {id: "private-and-user-prefix", kind: "ClassDeclaration", table: "members", source: String.raw`class C { #x = 1; "__#1@#x" = 2; "\uD800" = 3; }`},
  {id: "numeric-keys", kind: "ClassDeclaration", table: "members", source: String.raw`class N { [1]: number; [-1]: number; [+1]: number; 1.0: number; }`},
];
const units = text => Array.from({length: text.length}, (_, i) => text.charCodeAt(i));
const sha = bytes => crypto.createHash("sha256").update(bytes).digest("hex");
const root = path.resolve(import.meta.dirname, "..");
const compilerSha = sha(fs.readFileSync(path.join(root, "vendor/typescript-6.0.3/lib/typescript.js")));
assert.equal(compilerSha, "569177652966bd528c319171c7dd22860dbf72bde116cbc4f644f1d02bb12e39");

if (process.argv[2] === "--case") {
  const input = cases[Number(process.argv[3])];
  const source = ts.createSourceFile("main.ts", input.source, ts.ScriptTarget.ES2015, true);
  assert.equal(source.parseDiagnostics.length, 0);
  ts.bindSourceFile(source, {target: ts.ScriptTarget.ES2015});
  let selected;
  function visit(node) {
    if (!selected && node.kind === ts.SyntaxKind[input.kind]) selected = node;
    ts.forEachChild(node, visit);
  }
  visit(source);
  assert.ok(selected);
  const table = input.table === "locals" ? selected.locals : selected.symbol[input.table];
  const observation = {
    entries: Array.from(table, ([key, symbol]) => ({units: units(key), declarations: symbol.declarations?.length ?? 0})),
    patterns: source.patternAmbientModules?.map(p => [units(p.pattern.prefix), units(p.pattern.suffix)]) ?? [],
    diagnostics: source.bindDiagnostics.map(d => ({code: d.code, units: units(ts.flattenDiagnosticMessageText(d.messageText, "\n"))})),
  };
  console.log(JSON.stringify(observation));
} else {
  assert.ok(["--write", "--check"].includes(process.argv[2]));
  const observed = cases.map((input, index) => {
    function execute() {
      // getSymbolId's process counter must start independently for private names.
      const child = spawnSync(process.execPath, [import.meta.filename, "--case", String(index)], {encoding: "utf8"});
      assert.equal(child.status, 0, child.stderr);
      return JSON.parse(child.stdout);
    }
    const expected = execute();
    assert.deepEqual(execute(), expected, input.id);
    return {...input, kind_value: ts.SyntaxKind[input.kind], expected};
  });
  const rustUnits = value => `&[${value.join(", ")}]`;
  const content = [
    "// Generated by scripts/observe-utf16-binder-names.mjs; do not edit.",
    `// TypeScript 6.0.3 SHA-256: ${compilerSha}`,
    `// Observer SHA-256: ${sha(fs.readFileSync(import.meta.filename))}`,
    `// ${observed.length} cases, each observed twice in a fresh process. Binder API only.`,
    "const CASES: &[Case] = &[",
    ...observed.map(input => `    Case {\n        id: ${JSON.stringify(input.id)},\n        source: r####"${input.source}"####,\n        kind: ${input.kind_value}, table: ${JSON.stringify(input.table)},\n        entries: &[${input.expected.entries.map(e => `(${rustUnits(e.units)}, ${e.declarations})`).join(", ")}],\n        patterns: &[${input.expected.patterns.map(([a, b]) => `(${rustUnits(a)}, ${rustUnits(b)})`).join(", ")}],\n        diagnostics: &[${input.expected.diagnostics.map(d => `(${d.code}, ${rustUnits(d.units)})`).join(", ")}],\n    },`),
    "];", "",
  ].join("\n");
  const output = path.join(root, "crates/binder/tests/fixtures/utf16-binder-names.rs");
  if (process.argv[2] === "--write") {
    fs.mkdirSync(path.dirname(output), {recursive: true});
    fs.writeFileSync(output, content, {flag: "wx"});
  } else assert.equal(fs.readFileSync(output, "utf8"), content);
  console.log(JSON.stringify({output, sha256: sha(fs.readFileSync(output)), cases: cases.length, executions: cases.length * 2}));
}
