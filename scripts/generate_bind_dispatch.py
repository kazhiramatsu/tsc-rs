#!/usr/bin/env python3
"""Generate the binder's kind selection from the complete SyntaxKind enum."""
import argparse
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'crates/binder/src/bind_kind_dispatch.rs'


def generate():
    kind_source = (ROOT / 'crates/syntax/src/kind.rs').read_text()
    kinds = re.findall(r'^    (\w+) = (\d+),', kind_source, re.M)
    values = {name: int(value) for name, value in kinds}
    last_token = re.search(r'pub const LastToken: Self = Self::(\w+);', kind_source).group(1)
    source = (ROOT / 'crates/binder/src/bind.rs').read_text()
    start = source.index('    pub(crate) fn bind_worker(')
    end = source.index('\n    }', start) + len('\n    }')
    worker = source[start:end]
    # An unmentioned token can only reach the empty default arm. Including
    # nested kind tests is conservative and avoids a second action catalog.
    if not re.search(r'_ => \{\}\s*,?\s*\}\s*\}$', worker):
        raise ValueError('bind_worker default is no longer empty; review token continuations')
    active_tokens = set(re.findall(r'SyntaxKind::(\w+)', worker))
    no_action = [name for name, value in kinds if int(value) <= values[last_token] and name not in active_tokens]
    lines = [
        '// @generated by scripts/generate_bind_dispatch.py from SyntaxKind. Do not edit.',
        'use super::*;',
        "impl BinderWorker<'_> {",
        '/// Select the binding continuation once; each handler retains its constant kind.',
        '#[inline(always)]',
        'pub(super) fn bind_kind_dispatch(&mut self, node: NodeId, kind: SyntaxKind) {',
        'match kind {',
        ' | '.join('SyntaxKind::' + name for name in no_action) + ' => {',
        'if self.is_in_js_file() { self.bind_noop_token_in_js(node); }',
        '}',
    ]
    for name, _ in kinds:
        if name not in no_action:
            lines.append(f'SyntaxKind::{name} => self.bind_known_kind::<{{ SyntaxKind::{name} as u16 }}>(node),')
    lines += ['}', '}', '}', '']
    return subprocess.run(['rustfmt', '--edition', '2021'], input='\n'.join(lines), text=True, capture_output=True, check=True).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print('binder kind dispatch is stale; run scripts/generate_bind_dispatch.py')
            return 1
        print('generated binder kind dispatch is up to date')
        return 0
    OUTPUT.write_text(text)
    print('wrote', OUTPUT.relative_to(ROOT))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
