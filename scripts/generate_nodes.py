#!/usr/bin/env python3
"""Generate the syntax tree's node records and walks for tsc-rs.

usage: generate_nodes.py [--check]

Reads the field schema (crates/syntax/nodes.schema.json: every node kind's
payload fields in tsc's d.ts order, with their categories, and its children
in tsc's forEachChild order) and today's Rust layout of those records
(crates/syntax/nodes.layout.json: which payloads are boxed, the Rust type of
each text field, the JSDoc tags that visit their children in a conditional
order, the literal facts the node header keeps, field docs), and writes

  crates/syntax/src/nodes.rs              the records, NodeData, missing(), as_<kind>()
  crates/syntax/src/for_each_child.rs     forEachChild and the child-slot walks
  crates/syntax/src/relocate.rs           identity relocation, collection, remapping, equality
  crates/syntax/src/observable_fields.rs  the field view of the AST oracles

formatted by the toolchain's rustfmt. --check compares instead of writing
and exits 1 when any file differs. The parts that do not vary by kind (the
node header, the store records, the walk helpers) are templates below; every
per-kind line comes from the two data files, so a new record layout is a
change of data and templates, not of the generated files.
"""

