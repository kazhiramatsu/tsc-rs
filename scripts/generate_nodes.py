def rustfmt(text):
    result = subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input=text.encode(), cwd=ROOT, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
    )
    if result.returncode != 0:
        raise SystemExit("rustfmt failed:\n" + result.stderr.decode())
    return result.stdout.decode()


def generate():
    kinds, layout = load()
    return {
        OUTPUT_DIR / "nodes.rs": rustfmt(render_nodes_rs(kinds, layout)),
        OUTPUT_DIR / "for_each_child.rs": rustfmt(render_for_each_child_rs(kinds)),
        OUTPUT_DIR / "relocate.rs": rustfmt(render_relocate_rs(kinds)),
        OUTPUT_DIR / "observable_fields.rs": rustfmt(render_observable_fields_rs(kinds)),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="compare instead of writing; exit 1 on drift")
    args = parser.parse_args()
    outputs = generate()
    if args.check:
        stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is not what the node schema and layout generate", file=sys.stderr)
        if stale:
            print("run scripts/generate_nodes.py", file=sys.stderr)
            return 1
        print("generated node files are up to date")
        return 0
    for path, text in outputs.items():
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
