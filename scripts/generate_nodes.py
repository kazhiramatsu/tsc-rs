#!/usr/bin/env python3
"""Generate the syntax tree's node records and walks for tsc-rs.

usage: generate_nodes.py [--check]

Reads the field schema (crates/syntax/nodes.schema.json: every node kind's
payload fields in tsc's d.ts order, with their categories, and its children
in tsc's forEachChild order) and today's Rust layout of those records
(crates/syntax/nodes.layout.json: which payloads are boxed, the Rust type of
each text field, the JSDoc tags that visit their children in a conditional
order, the literal facts the node header keeps, field docs), and writes

  crates/syntax/src/nodes.rs              the records, NodeData, missing(), as_<kind>()
  crates/syntax/src/for_each_child.rs     forEachChild and the child-slot walks
  crates/syntax/src/relocate.rs           identity relocation, collection, remapping, equality
  crates/syntax/src/observable_fields.rs  the field view of the AST oracles

formatted by the toolchain's rustfmt. --check compares instead of writing
and exits 1 when any file differs. The parts that do not vary by kind (the
node header, the store records, the walk helpers) are templates below; every
per-kind line comes from the two data files, so a new record layout is a
change of data and templates, not of the generated files.
"""

import argparse
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "crates/syntax/nodes.schema.json"
LAYOUT = ROOT / "crates/syntax/nodes.layout.json"
OUTPUT_DIR = ROOT / "crates/syntax/src"
HEADER = (
    "// @generated by scripts/generate_nodes.py from crates/syntax/nodes.schema.json\n"
    "// and crates/syntax/nodes.layout.json. Do not edit by hand."
)

# The Rust type and missing() value of a text field, by the layout's
# stringTypes name; a text field the layout does not list is a `String`.
STRING_TYPES = {
    "String": ("String", "String::new()"),
    "JsString": ("tsc_types::JsString", "tsc_types::JsString::new()"),
    "EscapedName": (
        "tsc_types::EscapedName",
        'tsc_types::EscapedName::from_identifier_escaped_text("")',
    ),
}

SCALAR_TYPES = {"Bool": "bool", "SyntaxKind": "SyntaxKind", "JSDocComment": "JSDocComment"}
ID_TYPES = {"Node": "NodeId", "NodeArray": "NodeArrayId"}


class Field:
    def __init__(self, kind, raw, layout):
        self.ts_name = raw["name"]
        self.rust_name = raw["rustName"]
        self.ty = raw["type"]
        self.optional = raw["optional"]
        self.child = raw["child"]
        key = f"{kind}.{self.ts_name}"
        exception = layout.rust_optional.get(key)
        # Node and array children are Option-typed whatever the d.ts says:
        # the layout every parser, binder and checker site is written
        # against (`NodeData::missing` fills None).
        self.rust_optional = self.optional or self.child or exception is not None
        self.string_type = layout.string_types.get(key, "String") if self.ty == "String" else None
        self.docs = layout.field_docs.get(key, [])
        self.compared = key not in layout.equality_skips

    def base_type(self):
        if self.ty in ID_TYPES:
            return ID_TYPES[self.ty]
        if self.ty == "String":
            return STRING_TYPES[self.string_type][0]
        return SCALAR_TYPES[self.ty]

    def rust_type(self):
        base = self.base_type()
        return f"Option<{base}>" if self.rust_optional else base

    def missing_value(self, kind):
        if self.rust_optional:
            return "None"
        if self.ty == "String":
            return STRING_TYPES[self.string_type][1]
        return {
            "Node": "NodeId::default()",
            "NodeArray": "NodeArrayId::default()",
            "Bool": "false",
            "SyntaxKind": f"SyntaxKind::{kind}",
            "JSDocComment": "JSDocComment::Text { text: String::new(), pos: 0, end: 0, text_end: 0 }",
        }[self.ty]

    def is_identity(self):
        return self.ty in ("Node", "NodeArray", "JSDocComment")


class Kind:
    def __init__(self, raw, layout):
        self.name = raw["kindName"]
        self.data_name = raw["dataName"]
        self.fields = [Field(self.name, field, layout) for field in raw["fields"]]
        self.children = [(child["name"], child["array"]) for child in raw["children"]]
        self.boxed = self.name in layout.boxed
        self.visit_order = layout.visit_order.get(self.name)
        self.header_observables = [
            entry for entry in layout.header_observables if entry["kind"] == self.name
        ]

    def field(self, ts_name):
        for field in self.fields:
            if field.ts_name == ts_name:
                return field
        raise SystemExit(f"{self.name}: child {ts_name} has no field in the schema")

    def child_fields(self):
        return [(self.field(name), array) for name, array in self.children]


class Layout:
    def __init__(self, raw, kinds):
        names = {kind["kindName"] for kind in kinds}
        self.record = raw["record"]
        self.boxed = set()
        for group in raw["boxed"]:
            require_reason(group, "boxed group")
            for kind in group["kinds"]:
                if kind not in names or kind in self.boxed:
                    raise SystemExit(f"nodes.layout.json: boxed kind {kind} is unknown or repeated")
                self.boxed.add(kind)
        fields = {
            f"{kind['kindName']}.{field['name']}": field for kind in kinds for field in kind["fields"]
        }
        self.string_types = {}
        for name, entry in raw["stringTypes"].items():
            require_reason(entry, f"stringTypes.{name}")
            if name not in STRING_TYPES:
                raise SystemExit(f"nodes.layout.json: unknown string type {name}")
            for key in entry["fields"]:
                if fields.get(key, {}).get("type") != "String":
                    raise SystemExit(f"nodes.layout.json: {key} is not a String field")
                self.string_types[key] = name
        self.rust_optional = {}
        for key, why in raw["rustOptional"].items():
            if key not in fields or not why:
                raise SystemExit(f"nodes.layout.json: rustOptional {key} is unknown or has no reason")
            self.rust_optional[key] = why
        self.visit_order = {}
        for kind, entry in raw["visitOrder"].items():
            require_reason(entry, f"visitOrder.{kind}")
            schema = next((raw_kind for raw_kind in kinds if raw_kind["kindName"] == kind), None)
            children = [child["name"] for child in schema["children"]] if schema else []
            pair = entry["swap"]
            if (
                entry["when"] not in VISIT_ORDER_CONDITIONS
                or len(pair) != 2
                or pair[0] not in children
                or children.index(pair[0]) + 1 >= len(children)
                or children[children.index(pair[0]) + 1] != pair[1]
            ):
                raise SystemExit(f"nodes.layout.json: visitOrder {kind} names no adjacent child pair")
            self.visit_order[kind] = entry
        self.header_observables = raw["headerObservables"]
        for entry in self.header_observables:
            require_reason(entry, f"headerObservables {entry['kind']}.{entry['name']}")
            if entry["kind"] not in names:
                raise SystemExit(f"nodes.layout.json: headerObservables kind {entry['kind']} is unknown")
        self.equality_skips = {}
        for key, why in raw["equalitySkips"].items():
            if key not in fields or not why:
                raise SystemExit(f"nodes.layout.json: equalitySkips {key} is unknown or has no reason")
            self.equality_skips[key] = why
        self.field_docs = raw["fieldDocs"]
        for key in self.field_docs:
            if key not in fields:
                raise SystemExit(f"nodes.layout.json: fieldDocs {key} is unknown")


def require_reason(entry, what):
    if not entry.get("why"):
        raise SystemExit(f"nodes.layout.json: {what} has no reason ('why')")


def load():
    schema = json.loads(SCHEMA.read_text())
    raw_layout = json.loads(LAYOUT.read_text())
    layout = Layout(raw_layout, schema["nodes"])
    kinds = [Kind(raw, layout) for raw in schema["nodes"]]
    names = [kind.name for kind in kinds]
    if names != sorted(names):
        raise SystemExit("nodes.schema.json: kinds must be sorted by name")
    check_inline_payloads(kinds, layout)
    return kinds, layout


# Today's sizes (bytes, alignment) of a payload field's Rust type.
def field_size(field):
    if field.ty in ("Node", "NodeArray"):
        return 4, 4
    if field.ty == "Bool":
        return 1, 1
    if field.ty == "SyntaxKind":
        return 2, 2
    if field.ty == "String":
        return (4, 4) if field.string_type == "EscapedName" else (24, 8)
    if field.ty == "JSDocComment":
        return 40, 8
    raise SystemExit(f"unknown field type {field.ty}")


def payload_size(kind):
    sizes = [field_size(field) for field in kind.fields]
    align = max((alignment for _, alignment in sizes), default=1)
    size = sum(bytes for bytes, _ in sizes)
    return (size + align - 1) // align * align, align


def check_inline_payloads(kinds, layout):
    """An unboxed payload must fit NodeData's inline payload (4-byte aligned)."""
    limit = layout.record["inlinePayloadBytes"]
    for kind in kinds:
        size, align = payload_size(kind)
        if not kind.boxed and (size > limit or align > 4):
            raise SystemExit(
                f"nodes.layout.json: {kind.name}'s payload ({size} B, align {align}) "
                f"does not fit {limit} B inline: box it"
            )


def snake_case(name):
    out = ""
    for index, ch in enumerate(name):
        if not ch.isalnum():
            if not out.endswith("_"):
                out += "_"
            continue
        if index > 0 and ch.isupper():
            prev = name[index - 1]
            following = name[index + 1] if index + 1 < len(name) else ""
            splits = (prev.islower() or prev.isdigit()) or (prev.isupper() and following.islower())
            if splits and not out.endswith("_"):
                out += "_"
        out += ch.lower()
    return out.strip("_")


# The conditions of the layout's visitOrder entries: the opening of the
# branch that visits the swap pair in schema order.
VISIT_ORDER_CONDITIONS = {
    "isNameFirst": "if data.is_name_first {{",
    "typeExpressionIsJSDocTypeExpression": (
        "let type_expression_first = data.type_expression.is_some_and(|node| "
        "{node_kind} == SyntaxKind::JSDocTypeExpression);\nif type_expression_first {{"
    ),
}


