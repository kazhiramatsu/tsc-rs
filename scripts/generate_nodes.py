MAP_CHILD_SLOTS = r'''/// Map every slot through the visitor. Returns whether any slot changed.
pub fn map_child_slots<V>(slots: &mut ChildSlots, visitor: &mut V) -> Result<bool, V::Error>
where
    V: NodeDataChildVisitor,
{
    let mut changed = false;
    for slot in slots.as_mut_slice() {
        let mapped = match *slot {
            ChildSlot::Absent => continue,
            ChildSlot::Node(id) => ChildSlot::of_node(visitor.visit_node(id)?),
            ChildSlot::Nodes(id) => ChildSlot::of_nodes(visitor.visit_nodes(id)?),
            ChildSlot::JsDocNodes(id) => visitor.visit_nodes(id)?.map_or(ChildSlot::Absent, ChildSlot::JsDocNodes),
        };
        if mapped != *slot {
            changed = true;
            *slot = mapped;
        }
    }
    Ok(changed)
}
'''


def required_child_helpers(kinds):
    """Whether some kind has a required node, node-array or JSDoc comment
    child: the matching required-child helper is emitted only then."""
    node = nodes = jsdoc_comment = False
    for kind in kinds:
        for field, array in kind.child_fields():
            if field.rust_optional:
                continue
            if field.ty == "JSDocComment":
                jsdoc_comment = True
            elif not array:
                node = True
            else:
                nodes = True
    return node, nodes, jsdoc_comment


def for_each_child_line(kind, field, array):
    name = field.rust_name
    if field.ty == "JSDocComment":
        argument = f"data.{name}.as_ref()" if field.rust_optional else f"Some(&data.{name})"
        return (
            f"if let Some(result) = visit_optional_jsdoc_comment(lookup, {argument}, &mut cb) "
            "{ return Some(result); }"
        )
    if array:
        call = f"{'visit_optional_nodes' if field.rust_optional else 'visit_nodes'}(lookup, data.{name}, &mut cb)"
    else:
        call = f"{'visit_optional_node' if field.rust_optional else 'visit_node'}(data.{name}, &mut cb)"
    return f"if let Some(result) = {call} {{ return Some(result); }}"


def try_visit_line(kind, field, array):
    name = field.rust_name
    if field.ty == "JSDocComment":
        if field.rust_optional:
            return f"map_optional_jsdoc_comment(&mut data.{name}, visitor)?;"
        return f'map_jsdoc_comment(&mut data.{name}, SyntaxKind::{kind.name}, "{name}", visitor)?;'
    if field.rust_optional:
        return f"{'map_optional_nodes' if array else 'map_optional_node'}(&mut data.{name}, visitor)?;"
    helper = "map_required_nodes" if array else "map_required_node"
    return f'{helper}(&mut data.{name}, SyntaxKind::{kind.name}, "{name}", visitor)?;'


def child_slots_line(kind, field, array):
    name = field.rust_name
    if field.ty == "JSDocComment":
        argument = f"data.{name}.as_ref()" if field.rust_optional else f"Some(&data.{name})"
        return f"out.push(ChildSlot::of_jsdoc_comment({argument}));"
    if field.rust_optional:
        return f"out.push(ChildSlot::{'of_nodes' if array else 'of_node'}(data.{name}));"
    return f"out.push(ChildSlot::{'Nodes' if array else 'Node'}(data.{name}));"


def apply_child_slots_line(kind, field, array):
    name = field.rust_name
    if field.ty == "JSDocComment":
        if field.rust_optional:
            return f"apply_optional_jsdoc_comment(&mut data.{name}, next());"
        return f'apply_jsdoc_comment(&mut data.{name}, next(), SyntaxKind::{kind.name}, "{name}", visitor)?;'
    read = "nodes" if array else "node"
    if field.rust_optional:
        return f"data.{name} = next().{read}();"
    return (
        f"data.{name} = next().{read}().ok_or_else(|| "
        f'visitor.required_child_removed(SyntaxKind::{kind.name}, "{name}"))?;'
    )


def render_children(kind, out, line, node_kind):
    """The kind's children in visit order, one `line` each. A layout
    visitOrder pair is visited in schema order when its condition holds and
    swapped otherwise; `node_kind` renders the kind of the node `node`."""
    children = kind.child_fields()
    index = 0
    while index < len(children):
        field, array = children[index]
        if kind.visit_order and field.ts_name == kind.visit_order["swap"][0]:
            second = children[index + 1]
            condition = VISIT_ORDER_CONDITIONS[kind.visit_order["when"]].format(node_kind=node_kind)
            out += condition.split("\n")
            out += [line(kind, *children[index]), line(kind, *second), "} else {"]
            out += [line(kind, *second), line(kind, *children[index]), "}"]
            index += 2
            continue
        out.append(line(kind, field, array))
        index += 1


def render_for_each_child_rs(kinds):
    out = [HEADER, "", FOR_EACH_CHILD_PRELUDE]
    # The walks switch on the record's kind and decode that kind alone: no
    # NodeData is built for a walk.
    out.append("pub fn for_each_child<L, F>(lookup: &L, node: &Node, mut cb: F) -> Option<NodeId>")
    out += ["where", "L: NodeLookup,", "F: FnMut(NodeId) -> bool,", "{", "match node.kind {"]
    for kind in kinds:
        if not kind.children:
            continue
        out.append(f"SyntaxKind::{kind.name} => {{")
        out.append(f"let data = node.decode_{snake_case(kind.name)}();")
        render_children(kind, out, for_each_child_line, "lookup.node(node).kind")
        out += ["None", "}"]
    out += ["_ => None,", "}", "}", ""]

    out.append("pub fn for_each_child_array<F>(node: &Node, mut cb: F) -> Option<NodeArrayId>")
    out += ["where", "F: FnMut(NodeArrayId) -> bool,", "{", "match node.kind {"]
    for kind in kinds:
        arrays = [
            field for field, _ in kind.child_fields() if field.ty in ("NodeArray", "JSDocComment")
        ]
        if not arrays:
            continue
        out.append(f"SyntaxKind::{kind.name} => {{")
        out.append(f"let data = node.decode_{snake_case(kind.name)}();")
        for field in arrays:
            name = field.rust_name
            if field.ty == "NodeArray":
                if field.rust_optional:
                    out.append(f"if let Some(id) = data.{name} {{ if cb(id) {{ return Some(id); }} }}")
                else:
                    out.append(f"if cb(data.{name}) {{ return Some(data.{name}); }}")
            elif field.rust_optional:
                out.append(
                    f"if let Some(JSDocComment::Nodes(id)) = data.{name}.as_ref() "
                    "{ if cb(*id) { return Some(*id); } }"
                )
            else:
                out.append(
                    f"if let JSDocComment::Nodes(id) = &data.{name} {{ if cb(*id) {{ return Some(*id); }} }}"
                )
        out += ["None", "}"]
    out += ["_ => None,", "}", "}", ""]

    out.append(CHILD_VISITOR_TRAIT)
    out.append("/// `visitor` over the children of `data`, in forEachChild order. Always inlined:")
    out.append("/// where the variant is known (the parser's finish), only its children are walked.")
    out.append("#[inline(always)]")
    out.append("pub fn try_visit_each_child<V>(data: &mut NodeData, visitor: &mut V) -> Result<(), V::Error>")
    out += ["where", "V: NodeDataChildVisitor,", "{", "match data {"]
    out.append("NodeData::Token => Ok(()),")
    for kind in kinds:
        if not kind.children:
            out.append(f"NodeData::{kind.name}(_data) => Ok(()),")
            continue
        out.append(f"NodeData::{kind.name}(data) => {{")
        render_children(kind, out, try_visit_line, "visitor.node_kind(node)")
        out += ["Ok(())", "}"]
    out += ["}", "}", ""]

    out.append(MAP_HELPERS)
    required_node, required_nodes, required_jsdoc_comment = required_child_helpers(kinds)
    if required_node:
        out.append(MAP_REQUIRED_NODE)
    if required_nodes:
        out.append(MAP_REQUIRED_NODES)
    out.append(MAP_OPTIONAL_JSDOC_COMMENT)
    if required_jsdoc_comment:
        out.append(MAP_JSDOC_COMMENT)
    out.append(VISIT_HELPERS)
    max_children = max((len(kind.children) for kind in kinds), default=0)
    out.append(CHILD_SLOT_TYPES.replace("@MAX_CHILD_SLOTS@", str(max_children)))

    out.append("/// The children of `data` in [`try_visit_each_child`] order, without")
    out.append("/// cloning its payload. The visitor's `node_kind` answers the JSDocTypedefTag order.")
    out.append("pub fn child_slots<V: NodeDataChildVisitor>(data: &NodeData, visitor: &V) -> ChildSlots {")
    out += ["let mut out = ChildSlots::new();", "match data {", "NodeData::Token => {}"]
    for kind in kinds:
        if not kind.children:
            out.append(f"NodeData::{kind.name}(_data) => {{}}")
            continue
        out.append(f"NodeData::{kind.name}(data) => {{")
        render_children(kind, out, child_slots_line, "visitor.node_kind(node)")
        out.append("}")
    out += ["}", "out", "}", ""]

    out.append("/// Write mapped child slots back into `data`, in [`child_slots`] order.")
    out.append("/// A required child mapped to `Absent` reports `required_child_removed`.")
    out.append(
        "pub fn apply_child_slots<V>(data: &mut NodeData, slots: &ChildSlots, visitor: &mut V) "
        "-> Result<(), V::Error>"
    )
    out += ["where", "V: NodeDataChildVisitor,", "{"]
    out.append("let mut slots = slots.as_slice().iter().copied();")
    out.append("let mut next = || slots.next().unwrap_or(ChildSlot::Absent);")
    out += ["match data {", "NodeData::Token => Ok(()),"]
    for kind in kinds:
        if not kind.children:
            out.append(f"NodeData::{kind.name}(_data) => Ok(()),")
            continue
        out.append(f"NodeData::{kind.name}(data) => {{")
        render_children(kind, out, apply_child_slots_line, "visitor.node_kind(node)")
        out += ["Ok(())", "}"]
    out += ["}", "}", ""]
    out.append(APPLY_OPTIONAL_JSDOC_COMMENT)
    if required_jsdoc_comment:
        out.append(APPLY_JSDOC_COMMENT)
    out.append(MAP_CHILD_SLOTS)
    return "\n".join(out)


