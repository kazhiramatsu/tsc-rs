    render_identity_walk(kinds, out, COLLECT_FIELD, [])
    out += ["}", "}", ""]

    out.append(
        "/// Rewrite each identity of `data` (child nodes, node arrays, literal texts) through the three maps:"
    )
    out.append("/// a payload copied into another tree names that tree's nodes and texts.")
    out.append(
        "pub fn remap_node_data_ids<N, A, T>(data: &mut NodeData, mut node: N, mut array: A, mut text: T)"
    )
    out += [
        "where",
        "N: FnMut(NodeId) -> NodeId,",
        "A: FnMut(NodeArrayId) -> NodeArrayId,",
        "T: FnMut(TextId) -> TextId,",
        "{",
    ]
    out += ["match data {", "NodeData::Token => {}"]
    render_identity_walk(kinds, out, REMAP_FIELD, [])
    out += ["}", "}", ""]

    out.append(EQUALITY_HELPERS)
    out.append(
        "/// Whether two payloads are equal field by field, their identities compared through the three"
    )
    out.append("/// closures (a copied tree's ids differ; a text compares by content through `text`).")
    out.append(
        "pub fn node_data_structurally_equal<N, A, T>(left: &NodeData, right: &NodeData, "
        "mut node: N, mut array: A, mut text: T) -> bool"
    )
    out += [
        "where",
        "N: FnMut(NodeId, NodeId) -> bool,",
        "A: FnMut(NodeArrayId, NodeArrayId) -> bool,",
        "T: FnMut(TextId, TextId) -> bool,",
        "{",
    ]
    out += ["match (left, right) {", "(NodeData::Token, NodeData::Token) => true,"]
    for kind in kinds:
        left, right = ("left", "right") if kind.fields else ("_", "_")
        out.append(f"(NodeData::{kind.name}({left}), NodeData::{kind.name}({right})) => {{")
        if not kind.fields:
            out.append("true")
        for index, field in enumerate(field for field in kind.fields if field.compared):
            template = EQUAL_FIELD.get((field.walk_type(), field.rust_optional), "left.{0} == right.{0}")
            expression = template.format(field.rust_name)
            out.append(expression if index == 0 else f"&& {expression}")
        out.append("}")
    out += ["_ => false,", "}", "}"]
    return "\n".join(out) + "\n"


