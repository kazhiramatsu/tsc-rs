CHILD_SLOT_TYPES = r'''/// One child position of a node, as [`child_slots`] lists them and
/// [`apply_child_slots`] writes them back: the visit order and the
/// conditional JSDoc tag orders are those of [`try_visit_each_child`].
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ChildSlot {
    /// An absent optional child (or a JSDoc comment that is text).
    Absent,
    Node(NodeId),
    Nodes(NodeArrayId),
    /// A `JSDocComment::Nodes` comment.
    JsDocNodes(NodeArrayId),
}

/// The most children any node kind has.
pub const MAX_CHILD_SLOTS: usize = @MAX_CHILD_SLOTS@;

/// The child slots of one node, in [`child_slots`] order.
#[derive(Clone, Copy, Debug)]
pub struct ChildSlots {
    len: usize,
    slots: [ChildSlot; MAX_CHILD_SLOTS],
}

impl ChildSlots {
    pub const fn new() -> Self { Self { len: 0, slots: [ChildSlot::Absent; MAX_CHILD_SLOTS] } }
    fn push(&mut self, slot: ChildSlot) { self.slots[self.len] = slot; self.len += 1; }
    pub fn as_slice(&self) -> &[ChildSlot] { &self.slots[..self.len] }
    pub fn as_mut_slice(&mut self) -> &mut [ChildSlot] { &mut self.slots[..self.len] }
}

impl Default for ChildSlots {
    fn default() -> Self { Self::new() }
}

impl ChildSlot {
    fn of_node(id: Option<NodeId>) -> Self { id.map_or(Self::Absent, Self::Node) }
    fn of_nodes(id: Option<NodeArrayId>) -> Self { id.map_or(Self::Absent, Self::Nodes) }
    fn of_jsdoc_comment(comment: Option<&JSDocComment>) -> Self {
        match comment { Some(JSDocComment::Nodes(id)) => Self::JsDocNodes(*id), _ => Self::Absent }
    }
    fn node(self) -> Option<NodeId> { match self { Self::Node(id) => Some(id), _ => None } }
    fn nodes(self) -> Option<NodeArrayId> { match self { Self::Nodes(id) | Self::JsDocNodes(id) => Some(id), _ => None } }
}
'''

