def outputs():
    records, raw, kinds = load()
    binders = binder_fields(kinds)
    rs, tests, types = render_records(records)
    nodes, metrics = render_nodes(kinds, binders['kinds'], raw)
    syntax_kind = (ROOT / 'crates/syntax/src/kind.rs').read_text().split('#[cfg(test)]')[0]
    return {
        PREVIEW / 'src/records.rs': v1.rustfmt(rs),
        PREVIEW / 'tests/records_generated.rs': v1.rustfmt(tests),
        PREVIEW / 'tests/nodes_generated.rs': v1.rustfmt(render_node_tests(kinds)),
        PREVIEW / 'src/nodes.rs': v1.rustfmt(nodes),
        PREVIEW / 'src/syntax_kind.rs': HEADER + syntax_kind.rstrip() + '\n',
        PREVIEW / 'binder-fields.derived.json': dump(binders),
        PREVIEW / 'layout-metrics.json': dump({'nodes': metrics, 'types': types}),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    changed = []
    for path, content in outputs().items():
        if not path.exists() or path.read_text() != content:
            changed.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    if args.check and changed:
        print('stale generated files:\n' + '\n'.join(changed), file=sys.stderr)
        return 1
    print(f'{"checked" if args.check else "generated"} 7 files; 195 node kinds, 20 Type kinds')
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except ValueError as e:
        sys.exit(str(e))
