//! The node_modules buckets' package.json reading, package listing and
//! real path mapping (tsgo `packagejson.Parse`, `addPackageJsonDependencies`,
//! `getPackageNamesInNodeModules` and `getPackageRealpathFuncs`).

use std::collections::BTreeSet;

use tsc_host::MemoryCompilerHost;

use super::super::package_json::{add_package_json_dependencies, PackageJsonContents};
use super::*;

#[test]
fn package_json_dependencies_are_dependencies_and_peer_dependencies() {
    let contents = PackageJsonContents::parse(
        r#"{
            "dependencies": { "react": "*", "@types/node": "*", "@types/scope__pkg": "*" },
            "devDependencies": { "dev-only": "*" },
            "peerDependencies": { "peer": "*" },
            "optionalDependencies": { "optional": "*" },
            "bundledDependencies": { "bundled": "*" }
        }"#,
    );
    assert!(contents.parseable);
    let mut dependencies = BTreeSet::new();
    add_package_json_dependencies(&contents, &mut dependencies);
    assert_eq!(
        dependencies.into_iter().collect::<Vec<_>>(),
        ["@scope/pkg", "node", "peer", "react"]
    );
}

#[test]
fn package_json_fields_of_another_type_are_absent() {
    // tsgo reads a dependency field as a map of strings.
    let contents = PackageJsonContents::parse(
        r#"{ "dependencies": { "a": "*", "b": 1 }, "peerDependencies": { "c": "*" } }"#,
    );
    let mut dependencies = BTreeSet::new();
    add_package_json_dependencies(&contents, &mut dependencies);
    assert_eq!(dependencies.into_iter().collect::<Vec<_>>(), ["c"]);
    assert!(!PackageJsonContents::parse("{ not json").parseable);
    assert!(!PackageJsonContents::parse("[]").parseable);
}

#[test]
fn packages_of_a_node_modules_directory() {
    let host = MemoryCompilerHost::builder("/repo")
        .file("/repo/node_modules/plain/index.d.ts", b"".to_vec())
        .file("/repo/node_modules/@scope/pkg/index.d.ts", b"".to_vec())
        .file("/repo/node_modules/@types/node/index.d.ts", b"".to_vec())
        .file(
            "/repo/node_modules/@types/scope__typed/index.d.ts",
            b"".to_vec(),
        )
        .file("/repo/node_modules/.bin/tool", b"".to_vec())
        .build()
        .expect("a host");
    assert_eq!(
        get_package_names_in_node_modules("/repo/node_modules", &host)
            .into_iter()
            .collect::<Vec<_>>(),
        ["@scope/pkg", "@scope/typed", "node", "plain"]
    );
}

#[test]
fn a_linked_package_maps_its_files_by_prefix() {
    let host = MemoryCompilerHost::builder("/repo")
        .file("/repo/packages/lib/index.d.ts", b"".to_vec())
        .file("/repo/packages/dep/index.d.ts", b"".to_vec())
        .directory("/repo/node_modules/lib")
        .directory("/repo/node_modules/dep")
        .realpath("/repo/node_modules/lib", "/repo/packages/lib")
        .realpath("/repo/node_modules/dep", "/repo/packages/dep")
        .build()
        .expect("a host");
    let realpaths = PackageRealpaths::new(&host, "/repo/node_modules/lib");
    assert_eq!(
        realpaths.to_realpath("/repo/node_modules/lib/src/a.d.ts"),
        "/repo/packages/lib/src/a.d.ts"
    );
    // A file of another linked package is mapped by that package's directory.
    assert_eq!(
        realpaths.to_realpath("/repo/node_modules/dep/index.d.ts"),
        "/repo/packages/dep/index.d.ts"
    );
    assert_eq!(realpaths.to_realpath("/repo/src/a.ts"), "/repo/src/a.ts");
    assert_eq!(
        realpaths.to_symlink("/repo/packages/lib/src/a.d.ts"),
        "/repo/node_modules/lib/src/a.d.ts"
    );
    assert_eq!(
        realpaths.to_symlink("/repo/packages/dep/index.d.ts"),
        "/repo/packages/dep/index.d.ts"
    );
}
