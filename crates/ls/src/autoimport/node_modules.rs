/// tsgo `wrapvfs.Wrap(fs, Replacements{Realpath})`: a host whose real paths
/// are a package's (tsgo `getModuleResolver`).
pub(super) struct RealpathHost<'h> {
    pub(super) host: &'h dyn CompilerHost,
    pub(super) realpaths: &'h PackageRealpaths<'h>,
}

impl CompilerHost for RealpathHost<'_> {
    fn current_directory_js(&self) -> Result<JsString, HostError> {
        self.host.current_directory_js()
    }

    fn read_file_js(&self, path: JsStr<'_>) -> Result<Option<Vec<u8>>, HostError> {
        self.host.read_file_js(path)
    }

    fn file_size_hint_js(&self, path: JsStr<'_>) -> Result<Option<u64>, HostError> {
        self.host.file_size_hint_js(path)
    }

    fn file_exists_js(&self, path: JsStr<'_>) -> Result<bool, HostError> {
        self.host.file_exists_js(path)
    }

    fn directory_exists_js(&self, path: JsStr<'_>) -> Result<bool, HostError> {
        self.host.directory_exists_js(path)
    }

    fn read_directory_js(&self, path: JsStr<'_>) -> Result<Vec<JsString>, HostError> {
        self.host.read_directory_js(path)
    }

    fn read_directory_listing_js(
        &self,
        path: JsStr<'_>,
    ) -> Result<Vec<DirectoryListingEntry>, HostError> {
        self.host.read_directory_listing_js(path)
    }

    fn get_directories_js(&self, path: JsStr<'_>) -> Result<Vec<JsString>, HostError> {
        self.host.get_directories_js(path)
    }

    fn realpath_js(&self, path: JsStr<'_>) -> Result<Option<JsString>, HostError> {
        Ok(Some(JsString::from(
            self.realpaths.to_realpath(&path.to_string_lossy()).as_str(),
        )))
    }

    fn current_directory(&self) -> Result<PathBuf, HostError> {
        self.host.current_directory()
    }

    fn use_case_sensitive_file_names(&self) -> bool {
        self.host.use_case_sensitive_file_names()
    }

    fn read_file(&self, path: &Path) -> Result<Option<Vec<u8>>, HostError> {
        self.host.read_file(path)
    }

    fn file_exists(&self, path: &Path) -> Result<bool, HostError> {
        self.host.file_exists(path)
    }

    fn directory_exists(&self, path: &Path) -> Result<bool, HostError> {
        self.host.directory_exists(path)
    }

    fn read_directory(&self, path: &Path) -> Result<Vec<PathBuf>, HostError> {
        self.host.read_directory(path)
    }

    fn get_directories(&self, path: &Path) -> Result<Vec<PathBuf>, HostError> {
        self.host.get_directories(path)
    }

    fn realpath(&self, path: &Path) -> Result<Option<PathBuf>, HostError> {
        Ok(Some(PathBuf::from(
            self.realpaths.to_realpath(&path.to_string_lossy()),
        )))
    }
}

/// The real path of a file or directory through `host` (tsgo
/// `FS().Realpath`), the path itself when it has none.
pub(super) fn realpath(host: &dyn CompilerHost, path: &str) -> String {
    host.realpath_js(JsStr::from_str(path))
        .ok()
        .flatten()
        .map_or_else(
            || path.to_owned(),
            |path| path.to_string_lossy().into_owned(),
        )
}

/// tsgo `getPackageRealpathFuncs`: a package's files between their link and
/// real spellings, the host asked once per package directory.
pub(super) struct PackageRealpaths<'h> {
    host: &'h dyn CompilerHost,
    package_directory: String,
    real_package_directory: String,
    /// The real directories of the node_modules package directories files
    /// outside the package were found in.
    directory_cache: RefCell<HashMap<String, String>>,
}

impl<'h> PackageRealpaths<'h> {
    pub(super) fn new(host: &'h dyn CompilerHost, package_directory: &str) -> Self {
        Self {
            host,
            package_directory: package_directory.to_owned(),
            real_package_directory: realpath(host, package_directory),
            directory_cache: RefCell::default(),
        }
    }

    fn is_symlinked(&self) -> bool {
        self.real_package_directory != self.package_directory
    }

    /// tsgo `toRealpath`.
    pub(super) fn to_realpath(&self, file_name: &str) -> String {
        // Fast path: files within the package use prefix substitution.
        if self.is_symlinked() {
            if let Some(relative) = relative_to(file_name, &self.package_directory) {
                return join(&self.real_package_directory, relative);
            }
        }
        // Files outside the package (e.g. re-exports into symlinked deps):
        // find the node_modules package directory, resolve it once, and cache.
        let Some(file_package_directory) =
            tsc_program::node_module_package_root(JsStr::from_str(file_name), false)
        else {
            return file_name.to_owned();
        };
        let mut file_package_directory = file_package_directory.to_string_lossy().into_owned();
        // The wrapped host also asks real paths of directories while
        // traversing them. The two parses differ only when the path may be a
        // package root, so establish its kind before using the package cache.
        if let Some(directory_package) =
            tsc_program::node_module_package_root(JsStr::from_str(file_name), true)
        {
            let directory_package = directory_package.to_string_lossy();
            if directory_package != file_package_directory
                && self
                    .host
                    .directory_exists_js(JsStr::from_str(file_name))
                    .unwrap_or(false)
            {
                file_package_directory = directory_package.into_owned();
            }
        }
        let real_directory = self
            .directory_cache
            .borrow_mut()
            .entry(file_package_directory.clone())
            .or_insert_with(|| realpath(self.host, &file_package_directory))
            .clone();
        if real_directory == file_package_directory {
            return file_name.to_owned();
        }
        match relative_to(file_name, &file_package_directory) {
            Some(relative) => join(&real_directory, relative),
            None => real_directory,
        }
    }

    /// tsgo `toSymlink`: a file within the package at its link.
    pub(super) fn to_symlink(&self, file_name: &str) -> String {
        if !self.is_symlinked() {
            return file_name.to_owned();
        }
        match relative_to(file_name, &self.real_package_directory) {
            Some(relative) => join(&self.package_directory, relative),
            None => file_name.to_owned(),
        }
    }
}

/// tsgo `RootedFilePath.RelativeTo`: the path of a file below a directory,
/// relative to it.
fn relative_to<'p>(file_name: &'p str, directory: &str) -> Option<&'p str> {
    let rest = file_name.strip_prefix(directory)?;
    if directory.ends_with('/') {
        return (!rest.is_empty()).then_some(rest);
    }
    rest.strip_prefix('/').filter(|rest| !rest.is_empty())
}

fn join(directory: &str, relative: &str) -> String {
    if directory.ends_with('/') {
        format!("{directory}{relative}")
    } else {
        format!("{directory}/{relative}")
    }
}

/// tsgo `getPackageNamesInNodeModules`: the packages of a `node_modules`
/// directory, an `@types` package as the package it types.
pub(super) fn get_package_names_in_node_modules(
    node_modules_directory: &str,
    host: &dyn CompilerHost,
) -> BTreeSet<String> {
    let directories = |path: &str| -> Vec<String> {
        host.get_directories_js(JsStr::from_str(path))
            .unwrap_or_default()
            .into_iter()
            .map(|entry| {
                tsc_program::base_file_name(entry.as_js())
                    .to_string_lossy()
                    .into_owned()
            })
            .collect()
    };
    let mut package_names = BTreeSet::new();
    for base_name in directories(node_modules_directory) {
        if base_name.starts_with('.') {
            continue;
        }
        if base_name.starts_with('@') {
            for scoped in directories(&join(node_modules_directory, &base_name)) {
                if base_name == "@types" {
                    package_names.insert(tsc_program::get_package_name_from_types_package_name(
                        &format!("@types/{scoped}"),
                    ));
                } else {
                    package_names.insert(format!("{base_name}/{scoped}"));
                }
            }
            continue;
        }
        package_names.insert(base_name);
    }
    package_names
}

/// tsgo `discoveredPackage`: a package of a bucket with its package.json and
/// real directory, and the `@types` package typing it when there is one.
pub(super) struct DiscoveredPackage {
    pub(super) package_name: String,
    pub(super) package_json: Arc<PackageJsonInfo>,
    pub(super) realpath: Option<String>,
    pub(super) types_package_json: Option<Arc<PackageJsonInfo>>,
    pub(super) types_realpath: Option<String>,
    /// The real directory is in the workspace, out of every node_modules.
    pub(super) is_local: bool,
}

/// tsgo `discoverBucketPackages`.
pub(super) fn discover_bucket_packages(
    package_names: &BTreeSet<String>,
    directory_name: &str,
    host: &dyn CompilerHost,
    current_directory: &str,
    path_of: &dyn Fn(&str) -> String,
) -> Vec<DiscoveredPackage> {
    package_names
        .iter()
        .map(|package_name| {
            let types_package_name = tsc_program::types_package_name(JsStr::from_str(package_name))
                .to_string_lossy()
                .into_owned();
            let package_json = Arc::new(PackageJsonInfo::read(
                host,
                &join(
                    directory_name,
                    &format!("node_modules/{package_name}/package.json"),
                ),
            ));
            let types_package_json = (*package_name != types_package_name)
                .then(|| {
                    PackageJsonInfo::read(
                        host,
                        &join(
                            directory_name,
                            &format!("node_modules/{types_package_name}/package.json"),
                        ),
                    )
                })
                .filter(|types| types.directory_exists)
                .map(Arc::new);
            let package_realpath = package_json
                .directory_exists
                .then(|| realpath(host, &package_json.directory));
            let types_realpath = types_package_json
                .as_ref()
                .map(|types| realpath(host, &types.directory));
            let is_local = package_realpath.as_ref().is_some_and(|realpath| {
                !contains_lowercase_directory_sequence(realpath, "/node_modules/")
                    && contains_path(&path_of(current_directory), &path_of(realpath))
            });
            DiscoveredPackage {
                package_name: package_name.clone(),
                package_json,
                realpath: package_realpath,
                types_package_json,
                types_realpath,
                is_local,
            }
        })
        .collect()
}

/// tsgo `failedAmbientModuleLookupSource`: a file of an extraction that
/// failed to resolve a non-relative module.
#[derive(Clone, Debug)]
pub(super) struct FailedSource {
    pub(super) file_name: String,
    pub(super) package_name: String,
}

/// tsgo `perPackageExtractionResult`: one package directory's extraction,
/// installed into every bucket that has the package.
pub(super) struct PackageExtraction {
    /// The files indexed, path to name (a linked file's link too).
    pub(super) package_files: BTreeMap<String, String>,
    pub(super) entrypoints: Vec<Arc<ResolvedEntrypoint>>,
    /// The exports of each indexed file, by path.
    pub(super) exports: BTreeMap<String, Vec<Export>>,
    /// The files declaring each ambient module.
    pub(super) ambient_modules: BTreeMap<String, Vec<String>>,
    pub(super) is_symlinked: bool,
    pub(super) failed_sources: BTreeMap<String, FailedSource>,
    pub(super) failed_targets: BTreeSet<String>,
}

/// What a package's extraction reads.
pub(super) struct ExtractionInputs<'a> {
    pub(super) host: &'a (dyn CompilerHost + Sync),
    /// tsgo's parse cache: the documents the session's programs share.
    pub(super) documents: Option<&'a tsc_compiler::DocumentRegistry>,
    pub(super) path_of: &'a (dyn Fn(&str) -> String + Sync),
    /// tsgo `projectReferenceOutputs`: the source of each output .d.ts of
    /// the programs' project references, by the output's path.
    pub(super) project_reference_outputs: &'a BTreeMap<String, String>,
    /// tsgo `ParsedAutoImportFileExcludePatterns`.
    pub(super) file_exclude_patterns: Option<&'a tsc_program::vfsmatch::SpecMatcher>,
}

/// tsgo `extractPackage`: the exports of a package's entrypoints; none when
/// it has no entrypoint left.
pub(super) fn extract_package(
    inputs: &ExtractionInputs<'_>,
    package_json: &PackageJsonInfo,
    package_name: &str,
    enable_directory_search: bool,
) -> Option<PackageExtraction> {
    if !package_json.directory_exists {
        return None;
    }
    let realpaths = PackageRealpaths::new(inputs.host, &package_json.directory);
    let host = RealpathHost {
        host: inputs.host,
        realpaths: &realpaths,
    };
    let options = CompilerOptions::default();
    let mut resolver = ModuleResolver::new(&host, &options).ok()?;
    let mut package_entrypoints = resolver
        .get_entrypoints_from_package_json_info(
            JsStr::from_str(&package_json.directory),
            package_name,
            enable_directory_search,
        )
        .ok()?;

    if package_entrypoints.is_empty() {
        return None;
    }
    if let Some(patterns) = inputs.file_exclude_patterns {
        package_entrypoints
            .retain(|entrypoint| !patterns.match_string(&entrypoint.resolved_file_name));
    }
    if package_entrypoints.is_empty() {
        return None;
    }

    // Resolve entrypoint source files and build the alias resolver.
    let mut seen_files = BTreeSet::new();
    let mut root_files = Vec::new();
    // By real path: the link's path and name.
    let mut symlinks: BTreeMap<String, (String, String)> = BTreeMap::new();
    let mut is_symlinked = false;
    for entrypoint in &package_entrypoints {
        let mut file_name = entrypoint.symlink_or_realpath().to_owned();
        let mut realpath_file_name = entrypoint.resolved_file_name.clone();
        let mut realpath_path = (inputs.path_of)(&realpath_file_name);
        if let Some(input_file_name) = inputs.project_reference_outputs.get(&realpath_path) {
            file_name = realpaths.to_symlink(input_file_name);
            realpath_file_name = input_file_name.clone();
            realpath_path = (inputs.path_of)(&realpath_file_name);
        }
        if !seen_files.insert(realpath_path.clone()) {
            continue;
        }
        if file_name != realpath_file_name {
            symlinks.insert(realpath_path, ((inputs.path_of)(&file_name), file_name));
            is_symlinked = true;
        }
        root_files.push(realpath_file_name);
    }

    let to_realpath = |file_name: &str| realpaths.to_realpath(file_name);
    let extracted = extract_from_resolved_files(
        &host,
        inputs.documents,
        &mut resolver,
        &root_files,
        &[],
        inputs.path_of,
        /* record_failures */ true,
        |alias, resolver| {
            let mut resolve_module =
                |name: &str, containing_file: &str| resolve_from(resolver, name, containing_file);
            (0..alias.program_file_count)
                .map(|index| {
                    alias.with_checker(|checker| {
                        let source = checker.binder.source(index);
                        let ambient_module_names =
                            crate::references::collect_external_module_references(source)
                                .ambient_module_names;
                        let has_external_module_indicator =
                            source.external_module_indicator.is_some();
                        let mut extractor = Extractor {
                            checker,
                            path_of: inputs.path_of,
                            package_name: package_name.to_owned(),
                            realpath: Some(&to_realpath),
                            resolve_module: Some(&mut resolve_module),
                        };
                        let exports = extractor.extract_from_file(index).unwrap_or_default();
                        (exports, ambient_module_names, has_external_module_indicator)
                    })
                })
                .collect::<Vec<_>>()
        },
    );
    let mut result = PackageExtraction {
        package_files: BTreeMap::new(),
        entrypoints: Vec::new(),
        exports: BTreeMap::new(),
        ambient_modules: BTreeMap::new(),
        is_symlinked,
        failed_sources: BTreeMap::new(),
        failed_targets: BTreeSet::new(),
    };
    // A package none of whose entrypoints can be read keeps them all.
    let Some((alias, extracted)) = extracted else {
        result.entrypoints = package_entrypoints.into_iter().map(Arc::new).collect();
        return Some(result);
    };
    let mut non_module_files = BTreeSet::new();
    // The failed sources the package names: those its entrypoints were
    // when they were extracted.
    let mut named_sources = BTreeSet::new();
    for (index, extracted) in extracted.into_iter().enumerate() {
        let (file_name, path) = alias.files[index].clone();
        let Some((file_exports, ambient_module_names, has_external_module_indicator)) = extracted
        else {
            continue;
        };

        for name in ambient_module_names {
            result
                .ambient_modules
                .entry(name.to_string_lossy().into_owned())
                .or_default()
                .push(file_name.clone());
        }
        result.package_files.insert(path.clone(), file_name.clone());
        let symlink = symlinks.get(&path);
        if let Some((symlink_path, symlink_file_name)) = symlink {
            result
                .package_files
                .insert(symlink_path.clone(), symlink_file_name.clone());
        }
        let mut has_exports = !file_exports.is_empty() && has_external_module_indicator;
        let failed = alias.failed_lookups();
        if failed.sources.contains_key(&path) {
            named_sources.insert(path.clone());
            has_exports = has_external_module_indicator;
        } else {
            result.exports.insert(path.clone(), file_exports);
        }
        drop(failed);
        if !has_exports {
            non_module_files.insert(path.clone());
            if let Some((symlink_path, _)) = symlink {
                non_module_files.insert(symlink_path.clone());
            }
        }
    }
    {
        let failed = alias.failed_lookups();
        result.failed_targets = failed.targets.clone();
        result.failed_sources = failed
            .sources
            .iter()
            .map(|(path, file_name)| {
                let package_name = if named_sources.contains(path) {
                    package_name.to_owned()
                } else {
                    String::new()
                };
                (
                    path.clone(),
                    FailedSource {
                        file_name: file_name.clone(),
                        package_name,
                    },
                )
            })
            .collect();
    }
    // Discard entrypoints for non-module files and empty modules.
    result.entrypoints = package_entrypoints
        .into_iter()
        .filter(|entrypoint| !non_module_files.contains(&entrypoint.resolved_path))
        .map(Arc::new)
        .collect();
    Some(result)
}

/// tsgo `exportExtractor.moduleResolver.ResolveModuleName` of a relative
/// module augmentation's name: the file it resolves to (CommonJS mode).
pub(super) fn resolve_from(
    resolver: &mut ModuleResolver<'_>,
    name: &str,
    containing_file: &str,
) -> Option<String> {
    match resolver.resolve(
        JsStr::from_str(containing_file),
        JsStr::from_str(name),
        ResolutionMode::CommonJs,
    ) {
        Ok(ResolutionOutcome::Resolved(module)) => Some(
            module
                .resolved_file()
                .display()
                .to_string_lossy()
                .into_owned(),
        ),
        _ => None,
    }
}

/// tsgo `packageExtractionResult`: a bucket's packages' extractions.
#[derive(Default)]
pub(super) struct BucketExtraction {
    pub(super) exports: BTreeMap<String, Vec<Export>>,
    pub(super) package_files: BTreeMap<String, BTreeMap<String, String>>,
    pub(super) ambient_module_names: BTreeMap<String, Vec<String>>,
    pub(super) entrypoints: Vec<Vec<Arc<ResolvedEntrypoint>>>,
    pub(super) workspace_packages: BTreeSet<String>,
    pub(super) failed_sources: BTreeMap<String, FailedSource>,
    pub(super) failed_targets: BTreeSet<String>,
}

/// tsgo `installExtractions`.
pub(super) fn install_extractions(
    discovered: &[DiscoveredPackage],
    cache: &BTreeMap<String, PackageExtraction>,
) -> BucketExtraction {
    let mut result = BucketExtraction::default();
    for package in discovered {
        let extraction = package
            .realpath
            .as_ref()
            .and_then(|realpath| cache.get(realpath))
            .or_else(|| {
                package
                    .types_realpath
                    .as_ref()
                    .and_then(|realpath| cache.get(realpath))
            });
        let Some(extraction) = extraction else {
            continue;
        };
        for (path, exports) in &extraction.exports {
            result.exports.insert(path.clone(), exports.clone());
        }
        result
            .package_files
            .entry(package.package_name.clone())
            .or_default()
            .extend(
                extraction
                    .package_files
                    .iter()
                    .map(|(path, name)| (path.clone(), name.clone())),
            );
        for (name, file_names) in &extraction.ambient_modules {
            result
                .ambient_module_names
                .entry(name.clone())
                .or_default()
                .extend(file_names.iter().cloned());
        }
        result.entrypoints.push(extraction.entrypoints.clone());
        for (path, source) in &extraction.failed_sources {
            result
                .failed_sources
                .entry(path.clone())
                .or_insert_with(|| source.clone());
        }
        result
            .failed_targets
            .extend(extraction.failed_targets.iter().cloned());
        if extraction.is_symlinked && package.is_local {
            result
                .workspace_packages
                .insert(package.package_name.clone());
        }
    }
    result
}

