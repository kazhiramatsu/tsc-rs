pub(super) fn find(case_id: &str) -> Option<&'static Promotion> {
    CURRENT.iter().find(|row| row.case_id == case_id)
}

pub(super) fn validate(
    cases: &[Value],
    old_members: &HashMap<String, u64>,
) -> Result<(), Box<dyn Error>> {
    let mut ids = BTreeSet::new();
    for row in CURRENT {
        let case = cases
            .iter()
            .find(|case| case["case_id"] == row.case_id)
            .ok_or_else(|| failure(format!("{}: missing original output input", row.case_id)))?;
        if !ids.insert(row.case_id)
            || h2_6c_de_promotions::find(row.case_id).is_some()
            || old_members.get(row.case_id).copied().unwrap_or(0) != 0
            || case["disposition"] != "admitted-for-execution"
            || case["case_fingerprint_sha256"] != row.old_case_sha256
            || case["observation_input_sha256"] != row.old_input_sha256
            || sha256(serde_json::to_vec(compact_typescript_observation(case)?)?)
                != row.old_expected_tuple_sha256
        {
            return Err(failure(format!(
                "{}: original output promotion identity changed",
                row.case_id
            )));
        }
    }
    Ok(())
}

pub(super) fn declaration_members_total() -> u64 {
    CURRENT.iter().map(|row| row.declaration_members).sum()
}

pub(super) fn promoted_count() -> usize {
    CURRENT.len()
}

pub(super) fn adjusted_refusals(
    mut projected: BTreeMap<String, u64>,
) -> Result<BTreeMap<String, u64>, Box<dyn Error>> {
    for row in CURRENT {
        let count = projected
            .get_mut(row.old_refused_option)
            .ok_or_else(|| failure("missing historical output refusal bucket"))?;
        *count = count
            .checked_sub(1)
            .ok_or_else(|| failure("output refusal underflow"))?;
    }
    projected.retain(|_, count| *count != 0);
    Ok(projected)
}

pub(super) fn validate_results(
    results: &[Result<H2VectorCaseOutcome, String>],
    listed: &HashMap<String, H2VectorDivergence>,
) -> Result<(), Box<dyn Error>> {
    let mut seen = BTreeSet::new();
    for result in results {
        let outcome = result.as_ref().map_err(|error| failure(error.clone()))?;
        let Some(row) = find(&outcome.case_id) else {
            continue;
        };
        if !seen.insert(row.case_id)
            || outcome.deferred
            || !outcome.divergence.is_exact()
            || !outcome.divergence.mismatch_vector.is_empty()
            || outcome.h2_7b_activity != row.declaration_members
        {
            return Err(failure(format!(
                "{}: original output promotion no longer exact",
                row.case_id
            )));
        }
        if let Some(previous) = listed.get(row.case_id) {
            if *previous != vectorize_refusal(H2MismatchProfile::H2_6c, row.old_refused_option) {
                return Err(failure(format!(
                    "{}: original output refusal changed before promotion",
                    row.case_id
                )));
            }
        }
    }
    if seen.len() != CURRENT.len() {
        return Err(failure("original output promotion row was not executed"));
    }
    Ok(())
}
