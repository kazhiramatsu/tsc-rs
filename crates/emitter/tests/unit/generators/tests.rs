/// The §12.5 fixture resolver: `get_referenced_value_declaration` by
/// lexical catch-clause resolution over the single parse tree (exact for
/// the §7 fixture language, whose no-shadowing constraint keeps catch
/// names unclaimed by any inner binder); every other query inherits the
/// typed fail-closed defaults.
struct FixtureResolver {
    /// (name text, catch-block start, catch-block end, declaration node)
    catches: Vec<(String, u32, u32, NodeId)>,
    /// identifier node -> (text, position)
    identifiers: std::collections::BTreeMap<NodeId, (String, u32)>,
}

impl EmitResolver for FixtureResolver {
    fn get_referenced_value_declaration(
        &self,
        node: EmitResolverNode,
    ) -> Result<Option<EmitResolverNode>, EmitResolverError> {
        let Some((text, position)) = self.identifiers.get(&node.node()) else {
            return Ok(None);
        };
        let mut best: Option<(u32, NodeId)> = None;
        for (name, start, end, declaration) in &self.catches {
            if name == text
                && position >= start
                && position < end
                && best.map(|(s, _)| *start > s).unwrap_or(true)
            {
                best = Some((*start, *declaration));
            }
        }
        Ok(best.map(|(_, declaration)| EmitResolverNode::new(node.source(), declaration)))
    }
}

fn build_fixture_resolver(arena: &TransformArena, source: TransformSourceId) -> FixtureResolver {
    let syntax = arena
        .source(source)
        .expect("fixture source registered")
        .syntax();
    let node_base = syntax.arena.node_base();
    let mut catches = Vec::new();
    let mut identifiers = std::collections::BTreeMap::new();
    for (offset, record) in syntax.arena.nodes().iter().enumerate() {
        let id = NodeId(node_base + u32::try_from(offset).expect("node count fits u32"));
        match &record.data {
            NodeData::Identifier(data) => {
                identifiers.insert(id, (data.text.clone(), record.pos));
            }
            NodeData::CatchClause(data) => {
                let (Some(declaration), Some(block)) = (data.variable_declaration, data.block)
                else {
                    continue;
                };
                let declaration_record =
                    &syntax.arena.nodes()[(declaration.0 - node_base) as usize];
                let NodeData::VariableDeclaration(variable) = &declaration_record.data else {
                    continue;
                };
                let Some(name) = variable.name else { continue };
                let name_record = &syntax.arena.nodes()[(name.0 - node_base) as usize];
                let NodeData::Identifier(name_data) = &name_record.data else {
                    continue;
                };
                let block_record = &syntax.arena.nodes()[(block.0 - node_base) as usize];
                catches.push((
                    name_data.text.clone(),
                    block_record.pos,
                    block_record.end,
                    declaration,
                ));
            }
            _ => {}
        }
    }
    FixtureResolver {
        catches,
        identifiers,
    }
}

fn project(source_text: &str) -> String {
    let parsed = parse_source_file("input.ts", source_text, Default::default(), None);
    let mut arena = TransformArena::new();
    let source = arena.add_source(&parsed, Some(SourceFileId::from_raw(0)));
    let resolver = build_fixture_resolver(&arena, source);
    let mut result = transform_nodes(
        arena,
        vec![TransformRoot::SourceFile(source)],
        vec![transform_generators(
            tsc_types::ScriptTarget::ES5,
            &resolver,
        )],
        false,
    )
    .expect("generators transform");
    create_printer(
        PrinterOptions::new(NewLineKind::LineFeed).with_target(tsc_types::ScriptTarget::ES5),
    )
    .print(&mut result, PrintRequest::SourceFile(source), None)
    .expect("print generators projection")
    .text()
    .to_owned()
}

